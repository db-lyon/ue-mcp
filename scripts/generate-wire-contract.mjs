/**
 * Writes the TS/C++ wire contract from scripts/wire-contract/contract.json.
 *
 *     node scripts/generate-wire-contract.mjs    (also a step of npm run generate)
 *
 * Outputs, all committed and all generated, never edited by hand:
 *   src/bridge/wire-contract.ts       the values, plus runtime.ts.tmpl, for the server
 *   scripts/lib/wire-contract.mjs     the same module as plain JS, for node scripts
 *   plugin/.../Public/MCPWireContract.h   the values for the C++ bridge
 *
 * The plain JS is the TS module put through the TypeScript compiler's
 * transpileModule, so the two cannot say different things.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = path.join(ROOT, "scripts", "wire-contract");

export const OUTPUTS = {
  ts: "src/bridge/wire-contract.ts",
  mjs: "scripts/lib/wire-contract.mjs",
  cpp: "plugin/ue_mcp_bridge/Source/UE_MCP_Bridge/Public/MCPWireContract.h",
};

const BANNER = "Generated by scripts/generate-wire-contract.mjs from scripts/wire-contract/contract.json. Do not edit; change the contract and run npm run generate.";

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

function assertAscii(value, where) {
  const text = JSON.stringify(value);
  if (!/^[\x20-\x7e]*$/.test(text)) throw new Error(`${where}: the contract holds only printable ASCII, so the C++ TEXT() literals need no encoding`);
}

/** A JS doc comment, wrapped at about 100 columns. */
function jsDoc(text, indent = "") {
  if (!text) return "";
  const words = text.split(/\s+/);
  const lines = [];
  let line = "";
  for (const w of words) {
    if (line && (line.length + w.length + 1) > 96) {
      lines.push(line);
      line = w;
    } else {
      line = line ? `${line} ${w}` : w;
    }
  }
  if (line) lines.push(line);
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`).join("\n")}\n${indent} */\n`;
}

const cppDoc = jsDoc;
const lit = (v) => JSON.stringify(v);
const tchar = (v) => `TEXT(${JSON.stringify(v)})`;

function constObject(obj, indent = "  ") {
  const body = Object.entries(obj).map(([k, v]) => `${indent}${k}: ${lit(v)},`).join("\n");
  return `{\n${body}\n${indent.slice(2)}}`;
}

export function renderTs(c) {
  const out = [];
  // tests/unit/module-inventory.test.ts reads every src module's first line.
  out.push(`// @session independent: The generated wire contract; derives ports and record paths from the project root it is handed.\n// ${BANNER}\n`);
  out.push(`import { createHash } from "node:crypto";\nimport * as fs from "node:fs";\nimport * as os from "node:os";\nimport * as path from "node:path";\n`);

  out.push(jsDoc(c.versions.protocol.doc));
  out.push(`export const PROTOCOL_VERSION = ${c.versions.protocol.value};\n`);
  out.push(jsDoc(c.versions.handlerApi.doc));
  out.push(`export const HANDLER_API_VERSION = ${c.versions.handlerApi.value};\n`);

  out.push(jsDoc(c.features.doc));
  out.push(`export const BRIDGE_FEATURES = ${lit(c.features.values)} as const;\nexport type BridgeFeature = (typeof BRIDGE_FEATURES)[number];\n`);

  out.push(jsDoc(c.jsonRpcErrors.doc));
  out.push(`export const JSON_RPC_ERRORS = ${constObject(c.jsonRpcErrors.values)} as const;\n`);

  out.push(jsDoc(c.bridgeErrorCodes.doc));
  out.push(`export const BRIDGE_ERROR_CODES = ${constObject(c.bridgeErrorCodes.values)} as const;\n`);

  out.push(jsDoc(c.routingParams.doc));
  out.push(`export const ROUTING_PARAM_NAMES: readonly string[] = ${lit(c.routingParams.values)};\n`);

  out.push(jsDoc(c.batch.maxCalls.doc));
  out.push(`export const MAX_BATCH_CALLS = ${c.batch.maxCalls.value};\n`);

  out.push(jsDoc(c.bridgeState.doc));
  out.push(`export const BRIDGE_STATE = ${constObject(c.bridgeState.values)} as const;\nexport type BridgeState = (typeof BRIDGE_STATE)[keyof typeof BRIDGE_STATE];\n`);

  out.push(jsDoc(c.dialogRefusal.doc));
  out.push(`export const DIALOG_REFUSAL_FIELDS = ${constObject(c.dialogRefusal.fields)} as const;\n`);

  out.push(jsDoc(c.stateDir.doc));
  out.push(`export const STATE_DIR_SEGMENTS: readonly string[] = ${lit(c.stateDir.segments)};\n`);
  out.push(`export const INSTANCES_DIR_NAME = ${lit(c.stateDir.instancesDir)};\n`);
  out.push(`export const STATE_FILES = ${constObject(c.stateDir.files)} as const;\n`);

  out.push(`/** The field names of every record under the state directory. */\nexport const RECORD_FIELDS = {\n`);
  for (const [name, rec] of Object.entries(c.records)) {
    out.push(jsDoc(rec.doc, "  "));
    out.push(`  ${name}: ${constObject(rec.fields, "    ")},\n`);
  }
  out.push(`} as const;\n`);

  out.push(jsDoc(c.installKind.doc));
  out.push(`export const INSTALL_MARKER_FILE = ${lit(c.installKind.markerFile)};\nexport const INSTALL_KIND = ${constObject(c.installKind.values)} as const;\n`);
  out.push(`/** The bridge plugin's name, as its .uplugin and the plugin manager know it. */\nexport const BRIDGE_PLUGIN_NAME = ${lit(c.pluginName)};\n`);

  out.push(jsDoc(c.token.doc));
  const { doc: _tokenDoc, ...token } = c.token;
  out.push(`export const TOKEN = ${constObject(token)} as const;\n`);

  out.push(jsDoc(c.canvasReservedPorts.doc));
  out.push(`export const CANVAS_PLUGIN = ${lit(c.canvasReservedPorts.plugin)};\n`);
  out.push(`export const CANVAS_RESERVED_PORTS: readonly { readonly port: number; readonly use: string }[] = [\n${c.canvasReservedPorts.values.map((r) => `  { port: ${r.port}, use: ${lit(r.use)} },`).join("\n")}\n];\n`);

  out.push(jsDoc(c.checkpointManifest.doc));
  out.push(`export const CHECKPOINT_MANIFEST = {\n  file: ${lit(c.checkpointManifest.file)},\n  version: ${c.checkpointManifest.version},\n  fields: ${constObject(c.checkpointManifest.fields, "    ")},\n} as const;\n`);

  out.push(jsDoc(c.env.doc));
  out.push(`export const PLUGIN_ENV_VARS = ${constObject(c.env.values)} as const;\n`);

  out.push(jsDoc(c.port.doc));
  out.push(`export const DEFAULT_BRIDGE_PORT = ${c.port.default};\nexport const PORT_EPHEMERAL_BASE = ${c.port.ephemeralBase};\nexport const PORT_EPHEMERAL_SPAN = ${c.port.ephemeralSpan};\n`);
  out.push(`/** Roots and the ports both sides must derive for them. */\nexport const PORT_HASH_VECTORS: readonly { readonly root: string; readonly normalized: string; readonly port: number }[] = [\n${c.port.vectors.map((v) => `  { root: ${lit(v.root)}, normalized: ${lit(v.normalized)}, port: ${v.port} },`).join("\n")}\n];\n`);

  // A Windows checkout may hand the template over with CRLF; the outputs are LF.
  out.push(fs.readFileSync(path.join(SOURCE_DIR, "runtime.ts.tmpl"), "utf8").replace(/\r\n/g, "\n"));
  return out.join("\n");
}

export function renderMjs(tsSource) {
  const { outputText } = ts.transpileModule(tsSource, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, removeComments: false },
  });
  return outputText.replace(/\r\n/g, "\n");
}

function cppStrings(ns, obj, doc) {
  const lines = [cppDoc(doc, "\t"), `\tnamespace ${ns}\n\t{\n`];
  for (const [k, v] of Object.entries(obj)) lines.push(`\t\tinline constexpr const TCHAR* ${pascal(k)} = ${tchar(v)};\n`);
  lines.push(`\t}\n`);
  return lines.join("");
}

export function renderCpp(c) {
  const o = [];
  o.push(`// ${BANNER}\n\n#pragma once\n\n#include "CoreMinimal.h"\n\n`);
  o.push(cppDoc(c.versions.protocol.doc));
  o.push(`#define UEMCP_BRIDGE_PROTOCOL_VERSION ${c.versions.protocol.value}\n\n`);
  o.push(cppDoc(c.versions.handlerApi.doc));
  o.push(`#define UEMCP_BRIDGE_API_VERSION ${c.versions.handlerApi.value}\n\n`);
  o.push(`namespace UEMCPWire\n{\n`);

  o.push(cppDoc(c.features.doc, "\t"));
  o.push(`\tinline constexpr const TCHAR* Features[] = {\n${c.features.values.map((f) => `\t\t${tchar(f)},`).join("\n")}\n\t};\n\n`);

  o.push(cppDoc(c.jsonRpcErrors.doc, "\t"));
  o.push(`\tnamespace JsonRpcError\n\t{\n${Object.entries(c.jsonRpcErrors.values).map(([k, v]) => `\t\tinline constexpr int32 ${pascal(k)} = ${v};`).join("\n")}\n\t}\n\n`);

  o.push(cppStrings("BridgeErrorCode", c.bridgeErrorCodes.values, c.bridgeErrorCodes.doc), "\n");

  o.push(cppDoc(c.routingParams.doc, "\t"));
  o.push(`\tinline constexpr const TCHAR* RoutingParams[] = {\n${c.routingParams.values.map((f) => `\t\t${tchar(f)},`).join("\n")}\n\t};\n\n`);

  o.push(cppDoc(c.batch.maxCalls.doc, "\t"));
  o.push(`\tinline constexpr int32 MaxBatchCalls = ${c.batch.maxCalls.value};\n\n`);

  o.push(cppStrings("BridgeState", c.bridgeState.values, c.bridgeState.doc), "\n");
  o.push(cppStrings("DialogRefusalField", c.dialogRefusal.fields, c.dialogRefusal.doc), "\n");

  o.push(cppDoc(c.stateDir.doc, "\t"));
  o.push(`\tinline constexpr const TCHAR* StateDirSegments[] = {\n${c.stateDir.segments.map((f) => `\t\t${tchar(f)},`).join("\n")}\n\t};\n`);
  o.push(`\tinline constexpr const TCHAR* InstancesDirName = ${tchar(c.stateDir.instancesDir)};\n`);
  o.push(cppStrings("StateFile", c.stateDir.files, ""), "\n");

  for (const [name, rec] of Object.entries(c.records)) {
    o.push(cppStrings(`${pascal(name)}Field`, rec.fields, rec.doc), "\n");
  }

  o.push(cppDoc(c.installKind.doc, "\t"));
  o.push(`\tinline constexpr const TCHAR* InstallMarkerFile = ${tchar(c.installKind.markerFile)};\n`);
  o.push(cppStrings("InstallKind", c.installKind.values, ""), "\n");
  o.push(`\tinline constexpr const TCHAR* BridgePluginName = ${tchar(c.pluginName)};\n\n`);

  o.push(cppDoc(c.token.doc, "\t"));
  o.push(`\tnamespace Token\n\t{\n`);
  for (const [k, v] of Object.entries(c.token)) {
    if (k === "doc") continue;
    o.push(typeof v === "number" ? `\t\tinline constexpr int32 ${pascal(k)} = ${v};\n` : `\t\tinline constexpr const TCHAR* ${pascal(k)} = ${tchar(v)};\n`);
  }
  o.push(`\t}\n\n`);

  o.push(cppDoc(c.canvasReservedPorts.doc, "\t"));
  o.push(`\tinline constexpr const TCHAR* CanvasPlugin = ${tchar(c.canvasReservedPorts.plugin)};\n`);
  o.push(`\tinline constexpr int32 CanvasReservedPorts[] = { ${c.canvasReservedPorts.values.map((r) => r.port).join(", ")} };\n\n`);

  o.push(cppDoc(c.checkpointManifest.doc, "\t"));
  o.push(`\tnamespace CheckpointManifest\n\t{\n\t\tinline constexpr const TCHAR* File = ${tchar(c.checkpointManifest.file)};\n\t\tinline constexpr int32 Version = ${c.checkpointManifest.version};\n`);
  for (const [k, v] of Object.entries(c.checkpointManifest.fields)) o.push(`\t\tinline constexpr const TCHAR* ${pascal(k)}Field = ${tchar(v)};\n`);
  o.push(`\t}\n\n`);

  o.push(cppStrings("EnvVar", c.env.values, c.env.doc), "\n");

  o.push(cppDoc(c.port.doc, "\t"));
  o.push(`\tnamespace Port\n\t{\n\t\tinline constexpr int32 Default = ${c.port.default};\n\t\tinline constexpr int32 EphemeralBase = ${c.port.ephemeralBase};\n\t\tinline constexpr int32 EphemeralSpan = ${c.port.ephemeralSpan};\n\n`);
  o.push(`\t\tstruct FHashVector\n\t\t{\n\t\t\tconst TCHAR* Root;\n\t\t\tconst TCHAR* Normalized;\n\t\t\tint32 Port;\n\t\t};\n\n`);
  o.push(`\t\t/** Roots and the ports both sides must derive for them. */\n\t\tinline constexpr FHashVector HashVectors[] = {\n${c.port.vectors.map((v) => `\t\t\t{ ${tchar(v.root)}, ${tchar(v.normalized)}, ${v.port} },`).join("\n")}\n\t\t};\n\t}\n`);

  o.push(`}\n`);
  return o.join("");
}

export function loadContract() {
  const contract = JSON.parse(fs.readFileSync(path.join(SOURCE_DIR, "contract.json"), "utf8"));
  assertAscii(contract, "contract.json");
  for (const v of contract.port.vectors) {
    if (!Number.isInteger(v.port) || v.port < contract.port.ephemeralBase || v.port >= contract.port.ephemeralBase + contract.port.ephemeralSpan) {
      throw new Error(`contract.json: port vector for ${v.root} is outside the ephemeral range`);
    }
  }
  return contract;
}

/** Every output's path and the text it should hold. */
export function renderAll(contract = loadContract()) {
  const tsText = renderTs(contract);
  return {
    [OUTPUTS.ts]: tsText,
    [OUTPUTS.mjs]: renderMjs(tsText),
    [OUTPUTS.cpp]: renderCpp(contract),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [rel, text] of Object.entries(renderAll())) {
    const abs = path.join(ROOT, rel);
    // Compared without line endings, so a CRLF checkout is not rewritten for nothing.
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8").replace(/\r\n/g, "\n") : null;
    if (current !== text) {
      fs.writeFileSync(abs, text);
      console.log(`wrote ${rel}`);
    }
  }
}
